#!/usr/bin/env python3
"""Generate PIC18F8621_decompiled/parameters_explained.md from parameter_info.json (+ the baseline dumps)."""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "PIC18F8621_decompiled"))
from serial_gui import (INFO_PATH, BASELINE_GPL, BASELINE_GCL, FW_347, FW_35, parse_gpl, parse_gcl, read_lines,
                        fmt_value, decode_bits, rom_table)

info = json.load(open(INFO_PATH, encoding="utf-8"))
params, counters = parse_gpl(read_lines(BASELINE_GPL)), parse_gcl(read_lines(BASELINE_GCL))
out = ["# Parameters and counters explained (firmware T6 3.47V, plus v3.5.13 differences)", "",
       "Generated by `analysis/gen_param_doc.py` from `parameter_info.json` (edit that, then regenerate).",
       "Values are this unit's baseline (`write_tests/baseline_*.txt`). *(inferred)* marks meanings not fully proven.", "",
       "## Unit codes", "", "| Unit | Meaning |", "|---|---|"]
out += [f"| `{k}` | {v} |" for k, v in info["units"].items()]
groups = {}
for p in params:
    groups.setdefault(info["params"][p["name"]]["group"], []).append(p)
for g in sorted(groups):
    out += ["", f"## {g}", "", "| # | Name | Value | Default | Range | Meaning |", "|---|---|---|---|---|---|"]
    for p in groups[g]:
        pi = info["params"][p["name"]]
        f = lambda v: fmt_value(pi["unit"], v)
        desc = pi["desc"]
        if pi.get("bits"):
            desc += "<br>" + "<br>".join(f"`{l.strip()}`" for l in decode_bits(pi["bits"], p["value"]).splitlines())
        mark = " ✱" if p["value"] != p["default"] else ""
        out.append(f"| {p['i']} | `{p['name']}` | {p['value']} = {f(p['value'])}{mark} | {f(p['default'])} | "
                   f"{f(p['min'])} … {f(p['max'])} | {desc} |")
out += ["", "✱ = differs from the ROM default.", "", "## Usage counters", "", "| # | Name | Value | Meaning |", "|---|---|---|---|"]
for c in counters:
    ci = info["counters"][c["name"]]
    real = "" if ci["unit"] == "count" else f" = {fmt_value(ci['unit'], c['value'])}"
    out.append(f"| {c['i']} | `{c['name']}` | {c['value']:,}{real} | {ci['desc']} |")
old = {r["name"]: r for r in rom_table(info, FW_347)}
notes = info.get("versions", {}).get(FW_35, {}).get("notes", {})
out += ["", "## Firmware v3.5.13 differences", "",
        "v3.5.13 has 77 parameters (indexes 0-74 unchanged, two appended) and no serial command to read or write them "
        "(see `../v3.5.13/README.md`). ROM-table entries that differ from v3.47:", "",
        "| # | Name | v3.5.13 default / range | v3.47 | Meaning |", "|---|---|---|---|---|"]
for r in rom_table(info, FW_35):
    o, pi = old.get(r["name"]), info["params"][r["name"]]
    if o and (o["default"], o["min"], o["max"]) == (r["default"], r["min"], r["max"]):
        continue
    f = lambda v: fmt_value(pi["unit"], v)
    was = f"{f(o['default'])}, {f(o['min'])} … {f(o['max'])}" if o else "new"
    out.append(f"| {r['i']} | `{r['name']}` | {f(r['default'])}, {f(r['min'])} … {f(r['max'])} | {was} | "
               f"{pi['desc']}{'<br>' + notes[r['name']] if r['name'] in notes else ''} |")
out += ["", "Other v3.5.13 notes:", ""]
out += [f"* `{k}`: {v}" for k, v in notes.items() if k not in {r for r in info["versions"][FW_35]["rom"]}]
dst = os.path.join(os.path.dirname(INFO_PATH), "parameters_explained.md")
open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", dst)
